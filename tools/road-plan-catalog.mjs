// Keep the C++ assembly/port contract derived from the artist's catalogue.
import fs from 'node:fs';
import path from 'node:path';
export function roadPlanCatalog(root, checking) {
    const data = JSON.parse(fs.readFileSync(path.join(root, 'Resource/Documentation/road_plan_modules.json')));
    const number = n => Number(n.toFixed(7)).toString() + (Number.isInteger(Number(n.toFixed(7))) ? '.0f' : 'f');
    const xy = p => `{${number(p[0] * .5)}, ${number(p[1] * .5)}}`;
    const rows = ['// Generated by tools/road-plan-catalog.mjs from road_plan_modules.json. Do not edit.',
        'static const std::map<std::string, ArtModule> roadArt = {'];
    for (const [name, module] of Object.entries(data.modules)) {
        const ports = module.ports.filter(p => p.kind === 'road').map(p =>
            `{${xy(p.position_m)}, {${number(p.outward[0])}, ${number(p.outward[1])}}, ${p.lanes}}`);
        const companions = (module.companions ?? []).map(c =>
            `{"${c.module}", ${xy(c.position_m)}, ${number(c.position_m[2] * .5)}, ${number(c.yaw_degrees * Math.PI / 180)}}`);
        rows.push(`    {"${name}", {{${ports.join(', ')}}, {${companions.join(', ')}}}},`);
    }
    rows.push('};', '');
    const filename = path.join(root, 'SimpleGame/RoadPlanCatalog.h'), source = rows.join('\n');
    if (checking) {
        if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== source)
            throw Error('RoadPlanCatalog.h is stale; run node tools/pack-resources.mjs');
    } else fs.writeFileSync(filename, source);
    return data;
}
